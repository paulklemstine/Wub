#!/usr/bin/env python3
"""Incremental version control manager for Wub.

Increments the build / version code number automatically on git commit,
synchronizes version.json and frontend/src/version.ts, and updates static badges.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
from datetime import datetime, timezone
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parents[1]
VERSION_JSON = ROOT_DIR / "version.json"
VERSION_TS = ROOT_DIR / "frontend" / "src" / "version.ts"
INDEX_HTML = ROOT_DIR / "frontend" / "index.html"


def get_git_info() -> tuple[str, int]:
    """Get the current short commit hash and commit count."""
    try:
        commit = subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=ROOT_DIR,
            stderr=subprocess.DEVNULL,
            text=True,
        ).strip()
    except Exception:
        commit = "dev"

    try:
        count = int(
            subprocess.check_output(
                ["git", "rev-list", "--count", "HEAD"],
                cwd=ROOT_DIR,
                stderr=subprocess.DEVNULL,
                text=True,
            ).strip()
        )
    except Exception:
        count = 37

    return commit, count


def load_version_data() -> dict:
    if VERSION_JSON.exists():
        try:
            return json.loads(VERSION_JSON.read_text())
        except Exception:
            pass
    _, count = get_git_info()
    return {
        "major": 0,
        "minor": 2,
        "patch": count,
        "build": count,
        "version": f"0.2.{count}",
        "commit": "HEAD",
        "timestamp": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }


def write_version_ts(data: dict) -> None:
    content = f'''// Auto-generated by scripts/bump_version.py — DO NOT EDIT DIRECTLY
export interface VersionInfo {{
  major: number;
  minor: number;
  patch: number;
  build: number;
  version: string;
  commit: string;
  timestamp: string;
}}

export const VERSION_INFO: VersionInfo = {{
  major: {data["major"]},
  minor: {data["minor"]},
  patch: {data["patch"]},
  build: {data["build"]},
  version: "{data["version"]}",
  commit: "{data["commit"]}",
  timestamp: "{data["timestamp"]}",
}} as const;
'''
    VERSION_TS.parent.mkdir(parents=True, exist_ok=True)
    VERSION_TS.write_text(content)


def update_index_html(version_str: str, build_num: int, commit: str = "") -> None:
    if not INDEX_HTML.exists():
        return
    text = INDEX_HTML.read_text()
    changed = False

    badge_pattern = r'(<span class="mc-version-badge" id="mc-version-badge">)[^<]*(<span class="mc-build-num">)[^<]*(</span></span>)'
    badge_replacement = rf'\g<1>v{version_str} \g<2>#{build_num}\g<3>'
    if re.search(badge_pattern, text):
        new_text = re.sub(badge_pattern, badge_replacement, text)
        if new_text != text:
            text = new_text
            changed = True

    footer_pattern = r'(<span id="footer-version-tag"[^>]*>)[^<]*(</span>)'
    commit_suffix = f" • rev {commit}" if commit else ""
    footer_replacement = rf'\g<1>v{version_str} (Build #{build_num}{commit_suffix})\g<2>'
    if re.search(footer_pattern, text):
        new_text = re.sub(footer_pattern, footer_replacement, text)
        if new_text != text:
            text = new_text
            changed = True

    if changed:
        INDEX_HTML.write_text(text)


def main() -> None:
    parser = argparse.ArgumentParser(description="Bump or sync version control number.")
    parser.add_argument("--sync-only", action="store_true", help="Sync commit and timestamp without incrementing build number")
    parser.add_argument("--dry-run", action="store_true", help="Print version without modifying files")
    args = parser.parse_args()

    commit, count = get_git_info()
    data = load_version_data()

    if not args.sync_only:
        data["build"] = max(data.get("build", 0) + 1, count + 1)
        data["patch"] = data["build"]
        data["version"] = f"{data['major']}.{data['minor']}.{data['build']}"

    data["commit"] = commit
    data["timestamp"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    if args.dry_run:
        print(f"[dry-run] Version: {data['version']} (build {data['build']}, commit {data['commit']})")
        return

    # Write version.json
    VERSION_JSON.write_text(json.dumps(data, indent=2) + "\n")

    # Write frontend/src/version.ts
    write_version_ts(data)

    # Update frontend/index.html
    update_index_html(data["version"], data["build"], data["commit"])

    print(f"[version] Updated to v{data['version']} (Build #{data['build']} • rev {data['commit']})")

    # Automatically stage version files if invoked in git repository
    try:
        subprocess.run(
            ["git", "add", str(VERSION_JSON), str(VERSION_TS), str(INDEX_HTML)],
            cwd=ROOT_DIR,
            check=False,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
    except Exception:
        pass


if __name__ == "__main__":
    main()
